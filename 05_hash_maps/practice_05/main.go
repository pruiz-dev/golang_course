package main

import (
	"fmt"
	"time"
)

func main() {
	m := make(map[int]int)

	fmt.Println("Запускаем бомбу замедленного действия...")

	// Анонимная функция (go func), которая запускается в параллельном потоке
	go func() {
		for {
			m[1] = 1
		}
	}()

	// Основной поток (вторая горутина по умолчанию),
	// который тоже в бесконечном цикле пишет в эту же мапу.
	for {
		m[2] = 2
	}

	// Этот код никогда не выполнится
	time.Sleep(1 * time.Second)
}
